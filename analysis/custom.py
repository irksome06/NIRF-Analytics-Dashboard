"""Generic chart builder: any metric x aggregation x grouping x filters, drawn with a chart type that fits the result.

This is what lets the dashboard answer questions that are not among the 40 registered analyses. A request is a
plain dict (the "spec"); it is validated against the data and an allowlist, then executed with pandas. Nothing
generated by a language model is ever run as code.

    spec = {"metric": "TLR", "agg": "mean", "group_by": "state", "category": "Engineering", "year": 2022, "top_n": 10}
    data, fig, notes = build_chart(df, spec)

Spec fields (all optional):
    metric      score | TLR | RPC | GO | OI | PR | rank | count          what to measure ("count" = number of institutions)
    metric_y    same list, minus count                                    second metric: draws a scatter plot
    agg         mean | median | min | max | sum | count                   how to combine rows in each group
    group_by    year | state | category | city | institution | None       what each bar / point / box represents
    split_by    state | category | institution | None                     second dimension (series / heatmap rows)
    chart       auto | bar | line | scatter | box | histogram | heatmap
    category, categories, states, institutions, name_contains, year, year_from, year_to, rank_max,
    exact_only, top_n, sort (asc | desc)
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import plotly.graph_objects as go

from engine.data_loader import PARAM_NAMES, category_options, filter_data, resolve_institution, state_options, year_range
from engine.helpers import C, SERIES, style

METRICS = {"score": "Overall score", **{k: f"{k} ({v})" for k, v in PARAM_NAMES.items()}, "rank": "Rank", "count": "Number of institutions"}
SHORT = {"score": "overall score", "rank": "rank", "count": "number of institutions", **{k: k for k in PARAM_NAMES}}
AGGS = {"mean": "Average", "median": "Median", "min": "Lowest", "max": "Highest", "sum": "Total", "count": "Count"}
GROUPS = {"year": "year", "state": "state", "category": "category", "city": "city", "institution": "institution"}
SPLITS = {"state": "state", "category": "category", "institution": "institution"}
CHARTS = ["auto", "bar", "line", "scatter", "box", "histogram", "heatmap"]
GROUP_COL = {"year": "year", "state": "state", "category": "category", "city": "city", "institution": "institute_name"}
NAME_PATTERNS = {"IIT": "Indian Institute of Technology", "NIT": "National Institute of Technology", "IIM": "Indian Institute of Management",
                 "IIIT": "Indian Institute of Information Technology", "IISER": "Indian Institute of Science Education",
                 "AIIMS": "All India Institute of Medical Sciences", "NLU": "National Law", "BITS": "Birla Institute of Technology"}
ALLOWED = {"metric", "metric_y", "agg", "group_by", "split_by", "chart", "category", "categories", "states", "institutions", "name_contains",
           "year", "year_from", "year_to", "rank_max", "exact_only", "top_n", "sort"}


class CustomChartError(ValueError):
    """A request that cannot be drawn; the message says what to change."""


def _pick(value, allowed, label):
    if value is None:
        return None
    key = {str(a).lower(): a for a in allowed}.get(str(value).lower())
    if key is None:
        raise CustomChartError(f"{label} must be one of: {', '.join(map(str, allowed))}.")
    return key


def validate_spec(df: pd.DataFrame, spec: dict) -> tuple[dict, list[str]]:
    """Return (clean_spec, assumptions). Raises CustomChartError with a user-friendly message."""
    if not isinstance(spec, dict):
        raise CustomChartError("The chart request must be a dictionary.")
    extra = set(spec) - ALLOWED
    if extra:
        raise CustomChartError(f"Unsupported fields: {sorted(extra)}.")
    s = {k: v for k, v in spec.items() if v not in (None, "", [])}
    assumed: list[str] = []
    y0, y1 = year_range(df)
    cats, states = category_options(df), state_options(df)

    s["metric"] = _pick(s.get("metric", "score"), list(METRICS), "Metric")
    s["metric_y"] = _pick(s.get("metric_y"), [m for m in METRICS if m != "count"], "Second metric")
    s["agg"] = _pick(s.get("agg"), list(AGGS), "Aggregation") or ("count" if s["metric"] == "count" else "mean")
    s["group_by"] = _pick(s.get("group_by"), list(GROUPS), "Group by")
    s["split_by"] = _pick(s.get("split_by"), list(SPLITS), "Split by")
    s["chart"] = _pick(s.get("chart", "auto"), CHARTS, "Chart type")
    s["sort"] = _pick(s.get("sort"), ["asc", "desc"], "Sort")
    if s["split_by"] and s["split_by"] == s["group_by"]:
        s["split_by"] = None
    if s["metric_y"] and s["metric"] == "count":
        raise CustomChartError("A scatter plot needs two measures such as TLR and RPC, not a count.")
    if s["metric_y"] and s["chart"] == "auto":
        s["chart"] = "scatter"
    if s["chart"] == "scatter" and not s["metric_y"]:
        raise CustomChartError("A scatter plot needs a second measure (metric_y).")

    if s.get("category") is not None:
        s["category"] = _pick(s["category"], cats, "Category")
    if s.get("categories"):
        s["categories"] = [_pick(c, cats, "Category") for c in s["categories"]]
    if s["group_by"] != "category" and s["split_by"] != "category" and not s.get("category") and not s.get("categories"):
        s["category"] = "Overall"
        assumed.append("category Overall")
    if s.get("states"):
        s["states"] = [_pick(x, states, "State") for x in ([s["states"]] if isinstance(s["states"], str) else s["states"])]
    for k in ("year", "year_from", "year_to"):
        if k in s:
            try:
                s[k] = int(s[k])
            except (TypeError, ValueError):
                raise CustomChartError(f"{k} must be a year between {y0} and {y1}.")
            if not y0 <= s[k] <= y1:
                raise CustomChartError(f"Editions cover {y0}-{y1}; {s[k]} is outside that range.")
    if "year" in s:
        s["year_from"] = s["year_to"] = s.pop("year")
    if "year_from" in s and "year_to" in s and s["year_from"] > s["year_to"]:
        s["year_from"], s["year_to"] = s["year_to"], s["year_from"]
    for k, lo, hi, d in (("top_n", 1, 50, None), ("rank_max", 1, 1000, None)):
        if k in s:
            try:
                s[k] = int(s[k])
            except (TypeError, ValueError):
                raise CustomChartError(f"{k} must be a whole number.")
            if not lo <= s[k] <= hi:
                raise CustomChartError(f"{k} must be between {lo} and {hi}.")
    s["exact_only"] = bool(s.get("exact_only", True))
    if s.get("name_contains"):
        nc = str(s["name_contains"]).strip()
        s["name_contains"] = NAME_PATTERNS.get(nc.upper(), nc)
    if s.get("institutions"):
        names = []
        for i in ([s["institutions"]] if isinstance(s["institutions"], str) else s["institutions"]):
            hit = resolve_institution(df, str(i), s.get("category"))
            if hit.empty:
                raise CustomChartError(f"I could not find '{i}' in the data.")
            if len(hit) > 1:
                raise CustomChartError(f"'{i}' matches several institutions: " + "; ".join(hit["institute_name"].tolist()[:6]) + ". Please be more specific.")
            names.append(hit["institution_key"].iloc[0])
        s["institutions"] = names
    return s, assumed


def _fmt(v) -> str:
    return "n/a" if pd.isna(v) else (f"{v:,.0f}" if float(v).is_integer() else f"{v:,.1f}")


def describe(spec: dict) -> str:
    """One readable line: what is being drawn and with which filters."""
    m = SHORT[spec["metric"]]
    if spec.get("metric_y"):
        what = f"{m} against {SHORT[spec['metric_y']]}"
    elif spec["metric"] == "count":
        what = "Number of institutions"
    else:
        what = f"{AGGS[spec['agg']]} {m}"
    if spec.get("chart") == "box" and not spec.get("metric_y"):
        what = f"Spread of {m}"
    elif spec.get("chart") == "histogram":
        what = f"Distribution of {m}"
    by = f" by {spec['group_by']}" if spec.get("group_by") and not spec.get("metric_y") else ""
    split = f", split by {spec['split_by']}" if spec.get("split_by") else ""
    bits = []
    if spec.get("category"):
        bits.append(spec["category"])
    if spec.get("categories"):
        bits.append(" / ".join(spec["categories"]))
    if spec.get("states"):
        bits.append(", ".join(spec["states"]))
    if spec.get("name_contains"):
        bits.append(spec["name_contains"])
    if spec.get("year_from") is not None:
        bits.append(str(spec["year_from"]) if spec["year_from"] == spec.get("year_to") else f"{spec['year_from']}-{spec['year_to']}")
    if spec.get("rank_max"):
        bits.append(f"rank {spec['rank_max']} or better")
    return f"{what}{by}{split}" + (f" ({'; '.join(bits)})" if bits else "")


# ------------------------------------------------------------------ data
def _scope(df: pd.DataFrame, s: dict) -> pd.DataFrame:
    d = filter_data(df, category=s.get("category"), categories=s.get("categories"), states=s.get("states"),
                    institutions=s.get("institutions"), exact_only=False)
    if s.get("year_from") is not None:
        d = d[d["year"].between(s["year_from"], s.get("year_to", s["year_from"]))]
    if s.get("name_contains"):
        d = d[d["institute_name"].str.contains(s["name_contains"], case=False, regex=False)]
    return d


def _measure(d: pd.DataFrame, metric: str, exact_only: bool) -> tuple[pd.DataFrame, str, list[str]]:
    """Pick the column for a metric and drop rows where it is missing. Returns (rows, column, notes)."""
    notes: list[str] = []
    if metric == "count":
        return d, "institution_key", notes
    if metric == "rank":
        col = "rank" if exact_only else "rank_value"
        notes.append("Ranks are exact published ranks only." if exact_only else "Ranks include band midpoints, which are estimates.")
        return d[d[col].notna()], col, notes
    out = d[d[metric].notna()]
    if len(out) < len(d):
        notes.append("Scores exist only for institutions with a published exact rank, so charts of scores cover that group.")
    return out, metric, notes


def _label(s: dict, col: str) -> str:
    if s["metric"] == "count":
        return "Institutions"
    return f"{AGGS[s['agg']]} {SHORT[s['metric']]}"


def build_chart(df: pd.DataFrame, spec: dict) -> tuple[pd.DataFrame, go.Figure, list[str], dict]:
    """Validate, compute and draw. Returns (table, figure, notes, clean_spec)."""
    s, assumed = validate_spec(df, spec)
    notes = [f"Assumed {', '.join(assumed)} because none was given."] if assumed else []
    d = _scope(df, s)
    if d.empty:
        yrs = df[df["category"].eq(s["category"])]["year"] if s.get("category") else df["year"]
        raise CustomChartError("No institutions match these filters." + (f" {s['category']} has editions {int(yrs.min())}-{int(yrs.max())}." if len(yrs) else ""))
    if s.get("rank_max"):
        rc = "rank" if s["exact_only"] else "rank_value"
        d = d[d[rc].le(s["rank_max"])]
    d, col, n2 = _measure(d, s["metric"], s["exact_only"])
    notes += n2
    if d.empty:
        raise CustomChartError(f"None of the matching institutions has a published {SHORT[s['metric']]}. Try a wider year range or another category.")

    chart, g, sp = s["chart"], s["group_by"], s["split_by"]
    if chart == "auto":
        if s.get("metric_y"):
            chart = "scatter"
        elif g is None:
            multi_year = d["year"].nunique() > 1
            if s["metric"] == "count" or sp:
                g, chart = ("year" if multi_year else sp or "category"), "bar"
            elif multi_year and s["agg"] != "count":
                g, chart = "year", "line"
            else:
                chart = "histogram"
        elif g == "year":
            chart = "line"
        elif sp and sp != "year":
            chart = "heatmap" if d[GROUP_COL[g]].nunique() > 1 and d[GROUP_COL[sp]].nunique() > 1 and s["metric"] != "count" else "bar"
        else:
            chart = "bar"
    s["chart"], s["group_by"] = chart, g

    if chart == "scatter":
        return _scatter(df, d, s, notes)
    if chart == "histogram":
        return _histogram(d, col, s, notes)
    if chart == "box":
        return _box(d, col, s, notes)
    if g is None:
        raise CustomChartError("Choose what to group by (year, state, category, city or institution).")
    return _grouped(d, col, s, notes)


def _subtitle(d: pd.DataFrame, s: dict) -> str:
    bits = []
    if s.get("category"):
        bits.append(s["category"])
    if s.get("year_from") is not None:
        bits.append(str(s["year_from"]) if s["year_from"] == s.get("year_to") else f"{s['year_from']}-{s['year_to']}")
    if s.get("states"):
        bits.append(", ".join(s["states"][:3]))
    bits.append(f"{d['institution_key'].nunique():,} institutions")
    return " · ".join(bits)


def _grouped(d: pd.DataFrame, col: str, s: dict, notes: list[str]):
    g, sp, metric, agg = s["group_by"], s["split_by"], s["metric"], s["agg"]
    gcol = GROUP_COL[g]
    keys = [gcol] + ([GROUP_COL[sp]] if sp else [])
    if metric == "count" or agg == "count":
        t = d.groupby(keys).agg(value=("institution_key", "nunique"), n=("institution_key", "nunique")).reset_index()
    else:
        t = d.groupby(keys).agg(value=(col, agg), n=("institution_key", "nunique")).reset_index()
    if metric != "count" and metric not in ("rank",) and g == "category":
        notes.append("Scores are comparable only within the same weighting scheme, so compare categories with care.")
    asc = (s.get("sort") == "asc") if s.get("sort") else (metric == "rank")
    ordered_x = g == "year"
    top_n = s.get("top_n") or (None if ordered_x else 20)
    if not ordered_x:
        tot = t.groupby(gcol)["value"].agg("mean" if metric == "rank" or agg in ("mean", "median", "min", "max") else "sum")
        keep = tot.sort_values(ascending=asc).head(top_n).index.tolist()
        t = t[t[gcol].isin(keep)]
        t[gcol] = pd.Categorical(t[gcol], categories=keep, ordered=True)
        t = t.sort_values([gcol] + keys[1:]).reset_index(drop=True)
        t[gcol] = t[gcol].astype(str)
        if sp:
            sp_keep = t.groupby(keys[1])["n"].sum().sort_values(ascending=False).head(8).index
            t = t[t[keys[1]].isin(sp_keep)]
    else:
        t = t.sort_values(keys)
    label = _label(s, col)
    title = f"{label} by {g}" + (f" and {sp}" if sp else "")
    fig = go.Figure()
    fmt = ",.0f" if (metric == "count" or agg == "count") else ".1f"
    chart = s["chart"]
    if chart == "heatmap" and sp:
        p = t.pivot_table(index=keys[1], columns=gcol, values="value", aggfunc="mean", observed=True)
        p = p[[c for c in t[gcol].unique() if c in p.columns]]
        fig.add_trace(go.Heatmap(z=p.values, x=p.columns.astype(str), y=p.index, colorscale=[[0, "#F4F5FB"], [1, C["brand"]]],
                                 text=np.where(np.isnan(p.values), "", np.vectorize(lambda v: f"{v:{fmt}}")(np.nan_to_num(p.values))),
                                 texttemplate="%{text}", xgap=2, ygap=2, colorbar=dict(title=label, thickness=12),
                                 hovertemplate="%{y}, %{x}: %{z:.1f}<extra></extra>"))
        fig.update_yaxes(autorange="reversed")
        h = max(360, 34 * p.shape[0] + 180)
    elif chart == "line":
        series = [(None, t)] if not sp else list(t.groupby(keys[1]))
        for i, (name, part) in enumerate(series):
            fig.add_trace(go.Scatter(x=part[gcol], y=part["value"], mode="lines+markers", name=str(name) if name is not None else label,
                                     line=dict(color=SERIES[i % len(SERIES)], width=2.5), marker=dict(size=7),
                                     customdata=part["n"], hovertemplate=f"%{{x}}: %{{y:{fmt}}}<br>%{{customdata}} institutions<extra></extra>"))
        fig.update_xaxes(dtick=1 if g == "year" else None)
        fig.update_yaxes(title=label, rangemode="tozero" if metric in ("count",) else "normal")
        if metric == "rank":
            fig.update_yaxes(autorange="reversed")
        h = 440
    else:  # bar
        horizontal = not ordered_x
        series = [(None, t)] if not sp else list(t.groupby(keys[1]))
        for i, (name, part) in enumerate(series):
            kw = dict(y=part[gcol], x=part["value"], orientation="h") if horizontal else dict(x=part[gcol], y=part["value"])
            fig.add_trace(go.Bar(name=str(name) if name is not None else label, marker_color=SERIES[i % len(SERIES)] if sp else C["brand"],
                                 text=part["value"].map(lambda v: f"{v:{fmt}}"), textposition="outside", cliponaxis=False, customdata=part["n"],
                                 hovertemplate="%{" + ("y" if horizontal else "x") + "}: %{" + ("x" if horizontal else "y") + f":{fmt}}}<br>%{{customdata}} institutions<extra></extra>", **kw))
        if horizontal:
            fig.update_yaxes(autorange="reversed", automargin=True, categoryorder="array", categoryarray=list(t[gcol].unique()))
            fig.update_xaxes(title=label)
        else:
            fig.update_yaxes(title=label)
            fig.update_xaxes(type="category")
        if sp:
            fig.update_layout(barmode="group")
        h = max(380, 30 * len(t[gcol].unique()) * (len(series) if sp and horizontal else 1) + 160) if horizontal else 440
    style(fig, title, _subtitle(d, s), height=min(h, 900))
    if chart != "line" and s["agg"] in ("mean",) and t["n"].min() <= 2 and not sp:
        notes.append("Some averages rest on one or two institutions (see the n column).")
    if label == "Institutions":                       # the value is already the institution count: no duplicate column
        t = t.drop(columns="n")
        t = t.rename(columns={gcol: g.capitalize(), "value": label})
    else:
        t = t.rename(columns={gcol: g.capitalize(), "value": label, "n": "Institutions"})
    if sp:
        t = t.rename(columns={GROUP_COL[sp]: sp.capitalize()})
    return t, fig, notes, s


def _histogram(d: pd.DataFrame, col: str, s: dict, notes: list[str]):
    if s["metric"] == "count":
        raise CustomChartError("A histogram needs a score-type measure. Choose a group (year, state, ...) to count institutions.")
    v = d[col]
    fig = go.Figure(go.Histogram(x=v, nbinsx=20, marker_color=C["brand"], marker_line=dict(color="white", width=1),
                                 hovertemplate=f"{SHORT[s['metric']]} %{{x}}<br>%{{y}} institutions<extra></extra>"))
    fig.add_vline(x=v.median(), line_color=C["coral"], line_dash="dash", annotation_text=f"median {v.median():.1f}")
    fig.update_xaxes(title=METRICS[s["metric"]])
    fig.update_yaxes(title="Institutions (rows)")
    style(fig, f"Distribution of {SHORT[s['metric']]}", _subtitle(d, s))
    notes.append("Each institution-year is one observation.") if d["year"].nunique() > 1 else None
    return d[["institute_name", "year", "category", col]].rename(columns={col: SHORT[s["metric"]]}).reset_index(drop=True), fig, notes, s


def _box(d: pd.DataFrame, col: str, s: dict, notes: list[str]):
    g = s["group_by"]
    if g is None or s["metric"] == "count":
        raise CustomChartError("A box plot needs a score-type measure and a grouping (year, state, category, ...).")
    gcol = GROUP_COL[g]
    order = d.groupby(gcol)[col].agg("median").sort_values(ascending=(s["metric"] == "rank")).index.tolist()
    if g != "year":
        order = order[: (s.get("top_n") or 12)]
    else:
        order = sorted(order)
    fig = go.Figure()
    for k in order:
        fig.add_trace(go.Box(y=d.loc[d[gcol].eq(k), col], name=str(k), boxpoints="outliers", marker_color=C["brand"], line=dict(width=1.5), showlegend=False))
    fig.update_yaxes(title=METRICS[s["metric"]], autorange="reversed" if s["metric"] == "rank" else True)
    style(fig, f"Spread of {SHORT[s['metric']]} by {g}", _subtitle(d, s))
    t = d[d[gcol].isin(order)].groupby(gcol)[col].describe()[["count", "min", "25%", "50%", "75%", "max"]].round(2).reindex(order).reset_index()
    return t.rename(columns={gcol: g.capitalize(), "count": "Observations", "50%": "Median"}), fig, notes, s


def _scatter(df: pd.DataFrame, d: pd.DataFrame, s: dict, notes: list[str]):
    x, y = s["metric"], s["metric_y"]
    if x == y:
        raise CustomChartError("Choose two different measures for a scatter plot.")
    cols = {m: ("rank" if s["exact_only"] else "rank_value") if m == "rank" else m for m in (x, y)}
    d = d[d[cols[x]].notna() & d[cols[y]].notna()]
    if len(d) < 3:
        raise CustomChartError("Fewer than three institutions have both measures for these filters. Try a wider year range or another category.")
    if s["group_by"] == "institution":
        d = d.groupby("institute_name", as_index=False).agg({cols[x]: "mean", cols[y]: "mean", "category": "first", "state": "first", "year": "max", "institution_key": "first"})
    hover = d["institute_name"] + "<br>" + d["year"].astype(str) if "year" in d else d["institute_name"]
    fig = go.Figure(go.Scatter(x=d[cols[x]], y=d[cols[y]], mode="markers", text=hover, marker=dict(size=8, color=C["brand"], opacity=0.55, line=dict(color="white", width=0.5)),
                               hovertemplate="%{text}<br>" + f"{SHORT[x]} %{{x:.1f}}, {SHORT[y]} %{{y:.1f}}<extra></extra>"))
    r = float(np.corrcoef(d[cols[x]], d[cols[y]])[0, 1])
    if len(d) >= 5 and np.isfinite(r):
        b, a = np.polyfit(d[cols[x]], d[cols[y]], 1)
        xs = np.linspace(d[cols[x]].min(), d[cols[x]].max(), 20)
        fig.add_trace(go.Scatter(x=xs, y=a + b * xs, mode="lines", name="Trend", line=dict(color=C["amber"], width=2.5, dash="dash"), hoverinfo="skip"))
    fig.update_xaxes(title=METRICS[x])
    fig.update_yaxes(title=METRICS[y])
    if "rank" in (x, y):
        (fig.update_xaxes if x == "rank" else fig.update_yaxes)(autorange="reversed")
    fig.update_layout(showlegend=False)
    notes.append("Correlation is not causation; parameters feed the overall score, so strong links are partly built in.")
    style(fig, f"{SHORT[y].capitalize()} against {SHORT[x]}", _subtitle(d, s) + (f" · r = {r:.2f}" if np.isfinite(r) else ""))
    return d[["institute_name", "year", "category", cols[x], cols[y]]].reset_index(drop=True) if "year" in d else d.reset_index(drop=True), fig, notes, s
